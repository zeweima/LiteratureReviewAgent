"""Assemble a public release folder for the agentic literature-review framework.

The working repository mixes three kinds of material: code, aggregate results, and
raw per-paper extractions taken from the source literature. Most of that
literature is not open access, so the extracted prose cannot be redistributed.
This script builds a release tree containing the first two and deliberately
withholding the third, and it *verifies* the withholding rather than trusting the
copy list -- every shipped CSV is re-opened and checked for the columns that carry
source-derived prose.

What ships
    code    -- the full pipeline, synthesis, and audit scripts
    tables  -- aggregate statistics, cluster assignments, geographic summaries,
               and a corpus index reduced to bibliographic + coded fields
    figures -- every generated PNG
    reviews -- the agent-written review LaTeX and its table of contents

The evaluation material (extraction accuracy, citation fidelity) is withheld by
default and supplied separately by the author; --with-evaluation ships it.

What does not ship, and why
    long_<prose>.csv        per-paper statements written from the source papers
    papers_master free text  executive summaries, contributions, justifications
    citation_docs/           full text of the cited papers
    results/, log/           raw extraction payloads and run logs
    LLM/10.*/                per-paper reviewer workspaces
    by_field/*.csv           per-field extracted values plus verbatim quotes

The layout mirrors code/analysis/ exactly, so paths.py resolves unchanged and the
downstream scripts run against the shipped tables without edits.

Usage:
    python build_release.py                  # writes <repo>/release
    python build_release.py --out DIR        # elsewhere
    python build_release.py --dry-run        # report only, write nothing
"""

