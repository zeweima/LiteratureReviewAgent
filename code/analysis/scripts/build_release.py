def copy_tree(src: Path, dst: Path, keep=lambda p: True, dry=False) -> list[Path]:
    """Recursively copy, skipping SKIP_DIRS and anything `keep` rejects."""
    out = []
    if not src.is_dir():
        return out
    for p in sorted(src.rglob("*")):
        if any(part in SKIP_DIRS for part in p.relative_to(src).parts):
            continue
        if p.is_dir() or not keep(p):
            continue
        target = dst / p.relative_to(src)
        if not dry:
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(p, target)
        out.append(target)
    return out


def ship_master(src: Path, dst: Path, dry=False) -> tuple[int, list[str]]:
    """Copy papers_master keeping bibliographic and coded fields only.

    Written back under the original filename so the downstream scripts, which
    read the coded columns and never the prose ones, run unmodified.
    """
    d = pd.read_csv(src, low_memory=False)
    dropped = [c for c in MASTER_DROP if c in d.columns]
    d = d.drop(columns=dropped)
    if not dry:
        dst.parent.mkdir(parents=True, exist_ok=True)
        d.to_csv(dst, index=False, encoding="utf-8-sig")
    return len(d), dropped


def ship_tier1(src: Path, dst: Path, dry=False) -> int:
    """Curated extraction-error list, minus the verbatim source quotes.

    `llm_evidence` reproduces sentences from the source papers, so it is
    dropped; `extracted_content` is what our pipeline wrote and is what a
    reader needs to judge the error, so it stays.
    """
    d = pd.read_csv(src)
    d = d.drop(columns=[c for c in ("llm_evidence",) if c in d.columns])
    if not dry:
        dst.parent.mkdir(parents=True, exist_ok=True)
        d.to_csv(dst, index=False, encoding="utf-8-sig")
    return len(d)


def scan_imports(files: list[Path]) -> set[str]:
    """Top-level third-party modules imported by the given files.

    Takes the shipped file list rather than a source directory, so a dependency
    of code that was filtered out does not end up in requirements.txt.
    """
    local = {p.stem for p in files}
    mods = set()
    for p in files:
        try:
            tree = ast.parse(p.read_text(encoding="utf-8", errors="replace"))
        except SyntaxError:
            continue
        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                mods.update(a.name.split(".")[0] for a in node.names)
            elif isinstance(node, ast.ImportFrom) and node.level == 0 and node.module:
                mods.add(node.module.split(".")[0])
    stdlib = set(sys.stdlib_module_names)
    return {m for m in mods if m not in stdlib and m not in local}


def ship_agentic(A: Path, R: Path, dry: bool, with_statements: bool) -> dict:
    """Copy the synthesis tree: every stage's inputs, plans, and outputs.

    Three things are dropped for size rather than disclosure. Each unit
    directory carries a byte-identical copy of the same 1,946-entry
    references.bib (71 copies, 59 MB), so one master copy ships at the root
    instead. Per-unit compiled PDFs and TeX logs are build products of the
    shipped .tex and are dropped too.

    The one disclosure decision is inputs/fine/: those bundles are the extracted
    per-paper findings, and they ship only under --with-statement-inputs.
    """
    src = A / "latex" / "agentic"
    dst = R / "latex" / "agentic"
    KEEP = {".tex", ".md", ".json", ".jsonl", ".txt"}
    n, withheld = 0, 0

    for p in sorted(src.rglob("*")):
        if p.is_dir() or p.suffix not in KEEP:
            continue
        rel = p.relative_to(src)
        if any(part in SKIP_DIRS for part in rel.parts):
            continue
        # the fine-stage bundles are the extracted findings themselves
        if rel.parts[1:3] == ("inputs", "fine") and p.suffix == ".md":
            if not with_statements:
                withheld += 1
                continue
        if not dry:
            (dst / rel).parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(p, dst / rel)
        n += 1

    if not dry:
        master = src / "knowledge" / "overall" / "paper" / "references.bib"
        if master.is_file():
            shutil.copy2(master, dst / "references.bib")
        if withheld:
            for track in ("knowledge", "frontier"):
                d = dst / track / "inputs" / "fine"
                if d.is_dir():
                    (d / "README.md").write_text(FINE_INPUT_NOTE, encoding="utf-8")

    return {"files": n, "fine_bundles_withheld": withheld}


def scrub_paths(root: Path, repo: Path) -> int:
    """Rewrite absolute paths into the working checkout as repo-relative ones.

    The synthesis runner recorded where it read each input from, which bakes the
    author's home directory into the shipped unit manifests.
    """
    variants = [repo.as_posix() + "/", str(repo) + "\\", str(repo) + "/"]
    n = 0
    for p in sorted(root.rglob("*")):
        if p.is_dir() or p.suffix not in {".json", ".jsonl", ".md", ".tex", ".txt"}:
            continue
        try:
            t = p.read_text(encoding="utf-8")
        except (UnicodeDecodeError, OSError):
            continue
        if not any(v in t for v in variants):
            continue
        for v in variants:
            t = t.replace(v, "")
        p.write_text(t, encoding="utf-8")
        n += 1
    return n


def verify(root: Path) -> list[str]:
    """Re-open every shipped CSV and fail on a source-prose column."""
    problems = []
    for p in sorted(root.rglob("*.csv")):
        if p.name in EXEMPT_FILES:
            continue
        try:
            cols = set(pd.read_csv(p, nrows=0).columns)
        except Exception as e:  # noqa: BLE001
            problems.append(f"unreadable: {p.name} ({e})")
            continue
        bad = cols & FORBIDDEN_COLUMNS
        if bad:
            problems.append(f"{p.relative_to(root)} carries {sorted(bad)}")
    return problems


def build(repo: Path, out: Path, dry: bool = False, with_eval: bool = False,
          with_statements: bool = False) -> dict:
    A = repo / "code" / "analysis"
    S = repo / "code" / "assessment"
    R = out / "code" / "analysis"

    if out.exists() and not dry:
        shutil.rmtree(out)

    stats = {}

    # ---- code ------------------------------------------------------------
    # scripts/assessment implements the four-tier audit; it travels with the
    # evaluation material rather than with the pipeline.
    def want_script(p: Path) -> bool:
        if p.suffix not in {".py", ".md", ".ps1", ".sh", ".json"}:
            return False
        rel = p.relative_to(A / "scripts").parts
        if "assessment" not in rel:
            return True
        # common.py is a stdlib-only path/LaTeX helper that merge_final_reviews
        # imports, so it travels with the pipeline even when the audit does not
        return with_eval or p.name == "common.py"

    scripts = copy_tree(A / "scripts", R / "scripts", keep=want_script, dry=dry)
    stats["scripts"] = len(scripts)

    # ---- tables ----------------------------------------------------------
    T = A / "tables"
    shipped_tables = []
    for p in sorted(T.glob("*.csv")):
        n = p.name
        if n in PROSE_LONG:
            continue
        if n.startswith("papers_master"):
            continue                                   # handled below
        if n.startswith("long_") and n not in CODED_LONG:
            continue                                   # unclassified -> withhold
        if not dry:
            (R / "tables").mkdir(parents=True, exist_ok=True)
            shutil.copy2(p, R / "tables" / n)
        shipped_tables.append(n)
    stats["tables"] = len(shipped_tables)

    n_rows, dropped = ship_master(T / "papers_master.csv",
                                  R / "tables" / "papers_master.csv", dry)
    stats["corpus_index_rows"] = n_rows
    stats["master_columns_dropped"] = dropped
    if (T / "papers_master_normalized.csv").is_file():
        ship_master(T / "papers_master_normalized.csv",
                    R / "tables" / "papers_master_normalized.csv", dry)

    # ---- figures, docs, diagnostics --------------------------------------
    stats["figures"] = len(copy_tree(A / "figures", R / "figures",
                                     keep=lambda p: p.suffix == ".png", dry=dry))
    stats["docs"] = len(copy_tree(
        A / "docs", R / "docs",
        keep=lambda p: p.suffix == ".md" and p.name not in INTERNAL_DOCS, dry=dry))
    kd = [p for p in (A / "internal").glob("kdiag_*.csv")]
    for p in kd:
        if not dry:
            (R / "internal").mkdir(parents=True, exist_ok=True)
            shutil.copy2(p, R / "internal" / p.name)
    stats["diagnostics"] = len(kd)

    # ---- generated reviews ------------------------------------------------
    L = A / "latex" / "agentic"
    revs = []
    for p in sorted(L.glob("final_review_*.tex")):
        if not dry:
            (R / "latex" / "agentic").mkdir(parents=True, exist_ok=True)
            shutil.copy2(p, R / "latex" / "agentic" / p.name)
        revs.append(p.name)
    for track in ("knowledge", "frontier"):
        pdf = L / track / "overall" / "paper" / "main.pdf"
        if pdf.is_file():
            if not dry:
                shutil.copy2(pdf, R / "latex" / "agentic" / f"final_review_{track}.pdf")
            revs.append(f"final_review_{track}.pdf")
    box = A / "latex" / "box_review_structure.tex"
    if box.is_file() and not dry:
        shutil.copy2(box, R / "latex" / box.name)
    stats["reviews"] = revs
    stats["agentic"] = ship_agentic(A, R, dry, with_statements)

    # ---- evaluation -------------------------------------------------------
    # Withheld by default: the author assembles and supplies the validation
    # material separately. --with-evaluation ships the audit tables and the
    # curated extraction-error list (quotes stripped) instead.
    AU = out / "evaluation"
    if with_eval:
        n_audit = len(copy_tree(S / "report", AU / "citation_fidelity",
                                keep=lambda p: p.suffix in {".csv", ".md", ".mmd", ".png"},
                                dry=dry))
        t1 = S / "LLM" / "report" / "tier1_incorrect_fields.csv"
        if t1.is_file():
            stats["tier1_errors"] = ship_tier1(
                t1, AU / "extraction_accuracy" / "tier1_incorrect_fields.csv", dry)
        for f in ("REVIEW_INSTRUCTIONS.md", "PROMPT.md", "field_definitions.json"):
            p = S / "LLM" / f
            if p.is_file() and not dry:
                (AU / "extraction_accuracy").mkdir(parents=True, exist_ok=True)
                shutil.copy2(p, AU / "extraction_accuracy" / f)
        stats["evaluation"] = f"{n_audit} audit files"
    else:
        if not dry:
            AU.mkdir(parents=True, exist_ok=True)
            (AU / "README.md").write_text(PLACEHOLDER, encoding="utf-8")
        stats["evaluation"] = "withheld (placeholder written)"

    # ---- dependencies -----------------------------------------------------
    py = [p for p in (A / "scripts").rglob("*.py")
          if not any(part in SKIP_DIRS for part in p.parts) and want_script(p)]
    mods = scan_imports(py)
    known = sorted({PYPI[m] for m in mods if m in PYPI})
    stats["requirements"] = known
    stats["unmapped_imports"] = sorted(m for m in mods if m not in PYPI)
    if not dry:
        (out / "requirements.txt").write_text(
            "# minimum set inferred from imports in the shipped scripts\n"
            + "\n".join(known) + "\n", encoding="utf-8")

    if not dry:
        write_docs(out, stats)
        stats["paths_scrubbed"] = scrub_paths(out, repo)
    stats["problems"] = verify(out) if not dry else []
    return stats


README = """# Agentic literature review of subsurface (tile) drainage research

Code and derived results for a multi-agent framework that screens a literature
corpus, extracts structured evidence from each paper, discovers a nested theme
hierarchy from the extracted statements, and drafts a cited review from it.

The framework runs two independent content tracks over the same corpus:

* **knowledge** -- what the literature reports (`summary_bullets`, `highlights`)
* **frontier** -- what it says remains open (`future_directions`)

Each track is clustered and written separately, producing two reviews.

## Layout

```
code/analysis/
  scripts/          pipeline, clustering, figures, and the synthesis agents
  tables/           aggregate statistics and coded per-paper fields (CSV)
  figures/          all generated figures (PNG)
  docs/             methods notes and the agents' intermediate syntheses
  internal/         cluster-number diagnostics
  latex/agentic/    the generated reviews (LaTeX + PDF)
evaluation/         validation material, supplied separately
```

`scripts/paths.py` resolves every location relative to itself, so the tree runs
where it stands.

## Running it

```
pip install -r requirements.txt
cd code/analysis/scripts
python 3_geography.py            # and the other numbered stages
```

Stages differ in what they need, because the raw extractions are not
redistributable (see `DATA_AVAILABILITY.md`):

| Stage | Scripts | Runs from this release? |
|---|---|---|
| Extraction and flattening | `0_`-`2_` | No -- needs the per-paper extraction payloads |
| Geography, categories, cross-tabs | `3_`-`5_`, `3b_`, `4b_` | Yes |
| Clustering | `6_`, `7_` | No -- needs the extracted statement text to embed |
| Theme figures and tables | `8_`-`11_`, `kdiag` | Yes, from the shipped cluster assignments |
| Synthesis agents | `synth_agentic/` | Needs an API key and the statement text |

The clustering stage is the one break in the chain: its inputs are withheld, so
its *outputs* ship instead (`clusters_*.csv`, `stat_theme_hierarchy.csv`) and
everything downstream of it reproduces from those.

The geography scripts additionally expect basemap shapefiles under
`Data/Maps/BaseMap`, which are redistributed from their original public sources
rather than bundled here.

## Generated reviews

`code/analysis/latex/agentic/` holds the reviews as written by the agents, with
no human editing: `final_review_knowledge`, `final_review_frontier`, and the two
concatenated. `code/analysis/docs/final_review_toc.md` is their full section and
subsection structure.

## The synthesis run

Report generation is a three-stage cascade, and each stage's inputs and outputs
are here under `latex/agentic/<track>/`:

```
inputs/fine/       findings bundled per fine theme      -> written by prep_inputs
fine/              one drafted section per fine theme
inputs/macro/      the fine sections, regrouped
macro/             one drafted section per macro theme
inputs/overall/    the macro sections, plus the outline
overall/paper/     the assembled review
```

So the input to each stage is the previous stage's output, and the chain can be
read end to end: what the agent was given, what it was allowed to cite, and what
it wrote.

Alongside the drafts:

* `inputs/*/_units.json` -- each unit and the citation keys its writer was
  permitted to use. Citations are bounded structurally: a key outside this list
  is deleted before compile, so an unsupported citation cannot survive.
* `inputs/overall/_outline.json`, `_architect_raw.txt` -- the architect agent's
  plan, at subsection granularity, before any prose was written.
* `inputs/overall/_macro_digest.md` -- the condensed macro input to the architect.
* `tokens.jsonl` -- per-call token accounting.

`references.bib` sits once at `latex/agentic/`; every unit was compiled against
this same file, so the per-unit copies are not repeated. Per-unit PDFs and TeX
logs are build products of the shipped `.tex` and are omitted.

`inputs/fine/` is the one stage whose input is drawn from the source papers
rather than from a previous agent; see `DATA_AVAILABILITY.md`.
"""

