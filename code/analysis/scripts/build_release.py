def write_docs(out: Path, stats: dict) -> None:
    """Write the release-level documentation, with counts filled from stats."""
    summary = (
        f"\n## Contents of this build\n\n"
        f"* {stats.get('scripts', 0)} script files\n"
        f"* {stats.get('tables', 0)} result tables plus the "
        f"{stats.get('corpus_index_rows', 0):,}-paper corpus index\n"
        f"* {stats.get('figures', 0)} figures\n"
        f"* {stats.get('docs', 0)} documentation and synthesis notes\n"
    )
    (out / "README.md").write_text(README + summary, encoding="utf-8")
    (out / "DATA_AVAILABILITY.md").write_text(DATA_AVAILABILITY, encoding="utf-8")
    (out / "LICENSE.md").write_text(LICENSE_NOTE, encoding="utf-8")
    (out / ".gitignore").write_text(GITIGNORE, encoding="utf-8")


def main():
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--repo", default=None, help="repository root (default: inferred)")
    ap.add_argument("--out", default=None, help="release folder (default: <repo>/release)")
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--with-evaluation", action="store_true",
                    help="also ship the audit tables and the four-tier audit "
                         "scripts (default: withheld, author supplies them)")
    ap.add_argument("--with-statement-inputs", action="store_true",
                    help="also ship latex/agentic/*/inputs/fine/, the extracted "
                         "per-paper findings fed to the fine-stage writers "
                         "(default: withheld -- source-derived content)")
    args = ap.parse_args()

    here = Path(__file__).resolve()
    repo = Path(args.repo) if args.repo else here.parents[3]
    if not (repo / "code" / "analysis").is_dir():
        sys.exit(f"not a repository root: {repo}")
    out = Path(args.out) if args.out else repo / "release"

