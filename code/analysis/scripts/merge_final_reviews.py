"""Flatten the final reviews into self-contained LaTeX files.

The agentic pipeline emits each final review as a ``paper/`` directory whose
``main.tex`` ``\\input``s one file per section.  This script inlines those
section bodies so the full generated text can be read, diffed, or handed to a
co-author without walking two directory trees.

Three files are written: one per track, and one combining both under
``\\part`` headings.

Section order and the track titles are taken from each track's ``main.tex``
rather than from the directory listing, so the merged files follow the same
order the pipeline compiled.

Outputs (all under code/analysis/latex/agentic/):
    final_review_knowledge.tex
    final_review_frontier.tex
    final_review_both_tracks.tex

Usage:
    python merge_final_reviews.py
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(HERE / "assessment"))
from common import find_root  # noqa: E402

# track -> (part heading used in the combined file, single-track output name)
TRACKS = {
    "knowledge": ("Part I --- State of Knowledge", "final_review_knowledge.tex"),
    "frontier": ("Part II --- Research Frontier", "final_review_frontier.tex"),
}

COMBINED_NAME = "final_review_both_tracks.tex"
COMBINED_TITLE = (r"Tile Drainage: Agent-Generated Review\\[0.3em]"
                  r"\large State of Knowledge and Research Frontier")

HEADER = r"""% !TEX program = pdflatex
% ---------------------------------------------------------------------------
% Auto-generated by code/analysis/scripts/merge_final_reviews.py
% Do not edit by hand: regenerate instead.
%
% Section bodies are inlined verbatim from
%   code/analysis/latex/agentic/<track>/overall/paper/sections/
% SOURCES
% ---------------------------------------------------------------------------
\documentclass[11pt]{article}
\usepackage[utf8]{inputenc}
\usepackage[T1]{fontenc}
\usepackage{lmodern}
\usepackage[margin=1in]{geometry}
\usepackage{csquotes}
\usepackage[style=authoryear,backend=biber,sorting=nyt,maxbibnames=99,giveninits=true,uniquename=init]{biblatex}
\usepackage[hidelinks]{hyperref}
\addbibresource{../references.bib}
\title{TITLE}
\author{}
\date{}
\begin{document}
\maketitle
\tableofcontents
\clearpage
"""

TITLE_RE = re.compile(r"\\title\{(.+?)\}", re.DOTALL)
INPUT_RE = re.compile(r"\\input\{sections/(.+?)\}")


def read_main(paper_dir: Path) -> tuple[str, list[str]]:
    """Return (title, ordered section filenames) from a track's main.tex."""
    main = paper_dir / "main.tex"
    if not main.is_file():
        raise SystemExit(f"missing main.tex: {main}")
    text = main.read_text(encoding="utf-8")
    m = TITLE_RE.search(text)
    title = m.group(1).strip() if m else paper_dir.parent.parent.name
    names = INPUT_RE.findall(text)
    if not names:
        raise SystemExit(f"no \\input{{sections/...}} lines in {main}")
    return title, names


def load_track(agentic: Path, track: str) -> dict:
    """Read one track's title and inlined section bodies."""
    paper = agentic / track / "overall" / "paper"
    title, names = read_main(paper)
    sections = paper / "sections"

    bodies = []
    for name in names:
        fp = sections / name
        if not fp.is_file():
            raise SystemExit(f"missing section file: {fp}")
        bodies.append((name, fp.read_text(encoding="utf-8").strip()))

    return {
        "track": track,
        "title": title,
        "bodies": bodies,
        "sections": len(bodies),
        "chars": sum(len(b) for _, b in bodies),
    }


def header(title: str, sources: list[str]) -> str:
    note = "\n".join(f"%   {s}" for s in sources)
    return HEADER.replace("% SOURCES", note).replace(r"\title{TITLE}",
                                                     f"\\title{{{title}}}")


def render(title: str, parts: list[tuple[str | None, dict]]) -> str:
    """Assemble a full document from (part heading or None, track data) pairs."""
    sources = [f"{d['track']}/overall/paper/main.tex" for _, d in parts]
    chunks = [header(title, sources)]

    for part_title, data in parts:
        if part_title:
            chunks.append(f"\n\n\\part{{{part_title}}}\n")
        chunks.append(f"% ===== track: {data['track']} -- {data['title']} =====\n")
        for name, body in data["bodies"]:
            chunks.append(f"\n% ----- {data['track']}/{name} -----\n")
            chunks.append(body)
            chunks.append("\n")

    chunks.append("\n\n\\printbibliography\n\\end{document}\n")
    return "".join(chunks)


def build() -> dict:
    root = find_root(HERE)
    agentic = root / "code" / "analysis" / "latex" / "agentic"
    if not agentic.is_dir():
        raise SystemExit(f"missing latex tree: {agentic}")

    loaded = {t: load_track(agentic, t) for t in TRACKS}
    written = {}

    # one file per track
    for track, (_, out_name) in TRACKS.items():
        data = loaded[track]
        out_fp = agentic / out_name
        out_fp.write_text(render(data["title"], [(None, data)]), encoding="utf-8")
        written[out_name] = {"sections": data["sections"],
                             "chars": data["chars"],
                             "bytes": out_fp.stat().st_size}

    # both tracks in one file
    parts = [(TRACKS[t][0], loaded[t]) for t in TRACKS]
    out_fp = agentic / COMBINED_NAME
    out_fp.write_text(render(COMBINED_TITLE, parts), encoding="utf-8")
    written[COMBINED_NAME] = {
        "sections": sum(d["sections"] for d in loaded.values()),
        "chars": sum(d["chars"] for d in loaded.values()),
        "bytes": out_fp.stat().st_size,
    }

    return {"out_dir": str(agentic), "files": written}


if __name__ == "__main__":
    res = build()
    print(f"out_dir  {res['out_dir']}")
    for name, v in res["files"].items():
        print(f"  {name:34s} {v['sections']:3d} sections  "
              f"{v['chars']:7d} chars  {v['bytes']:7d} bytes")
